public static class Rec
{
    // Сумма цифр неотрицательного числа
    public static int DigitSum(int n)
    {
        // Базовый случай: если число однозначное (меньше 10), возвращаем само число
        if (n < 10)
        {
            return n;
        }
        
        // Рекурсивный шаг: последняя цифра + сумма цифр оставшейся части
        return (n % 10) + DigitSum(n / 10);
    }

    // Возведение x в степень n (n >= 0) без Math.Pow
    public static long Pow(int x, int n)
    {
        // Базовый случай: любое число в степени 0 равно 1
        if (n == 0)
        {
            return 1;
        }
        
        // Рекурсивный шаг: x умножается на x в степени (n - 1)
        return x * Pow(x, n - 1);
    }
}
